//! Storage-agnostic document access: the seam between the UI and MongoDB.

use async_trait::async_trait;
use bson::{Bson, Document};

use crate::compare::diff::PathSegment;
use crate::compare::key::{KeySpec, KeyTuple};
use crate::error::{CoreError, Result};

/// How the connected MongoDB server is deployed, as its `hello` reply tells.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Topology {
    Direct,
    ReplicaSet,
    Sharded,
}

/// Documents fetched per page in the browser.
pub const PAGE_SIZE: u64 = 50;

/// A database + collection pair. Names may contain dots, spaces or unicode.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct Namespace {
    pub db: String,
    pub collection: String,
}

impl Namespace {
    pub fn new(db: impl Into<String>, collection: impl Into<String>) -> Self {
        Self {
            db: db.into(),
            collection: collection.into(),
        }
    }
}

/// A find request: filter, optional sort/projection, and a skip/limit window.
#[derive(Clone, Debug, PartialEq)]
pub struct Query {
    pub filter: Document,
    pub sort: Option<Document>,
    pub projection: Option<Document>,
    pub skip: u64,
    pub limit: u64,
}

impl Default for Query {
    fn default() -> Self {
        Self {
            filter: Document::new(),
            sort: None,
            projection: None,
            skip: 0,
            limit: PAGE_SIZE,
        }
    }
}

/// One page of results. `has_more` is true when documents remain past `docs`.
#[derive(Clone, Debug, PartialEq)]
pub struct Page {
    pub docs: Vec<Document>,
    pub skip: u64,
    pub has_more: bool,
}

/// Whether an index can serve a compare's key-ordered scan.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum IndexStatus {
    Indexed,
    NotIndexed,
}

/// What a collection is. A view can be read but never written.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CollectionKind {
    Collection,
    View,
    Timeseries,
}

/// A key tuple shared by `count` (two or more) documents.
#[derive(Clone, Debug, PartialEq)]
pub struct DuplicateGroup {
    pub key: KeyTuple,
    pub count: u64,
}

/// One write against one collection. Matched by `_id`.
#[derive(Clone, Debug, PartialEq)]
pub enum WriteOp {
    /// `_id` is generated by the server when the doc has none.
    Insert {
        doc: Document,
    },
    /// `doc` carries the same `_id`.
    Replace {
        id: Bson,
        doc: Document,
    },
    Delete {
        id: Bson,
    },
    /// Updates named fields of the document with `_id == id`; the rest is untouched. Every path
    /// is a field-or-index address that the planner has already vetted (never `_id`, never an
    /// unordered-array element). A store that cannot render a segment fails the op.
    UpdateFields {
        id: Bson,
        set: Vec<(Vec<PathSegment>, Bson)>,
        unset: Vec<Vec<PathSegment>>,
    },
}

/// Why one write did not happen. Never carries server text or document values.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WriteFailure {
    /// Nothing matched `_id` (a Replace or Delete): the document is gone.
    Missing,
    /// A unique index (or `_id`) already holds that value.
    DuplicateKey,
    /// The server refused it; the numeric error code.
    Rejected(i32),
}

pub type WriteOutcome = std::result::Result<(), WriteFailure>;

#[async_trait]
pub trait DocumentStore: Send + Sync {
    async fn list_databases(&self) -> Result<Vec<String>>;
    async fn list_collections(&self, db: &str) -> Result<Vec<String>>;
    async fn find(&self, ns: &Namespace, q: &Query) -> Result<Page>;

    // WRITE METHODS (`insert`, `replace`, `delete`, `bulk_write`): `ReadOnlyStore` must refuse
    // each of them. Adding a write method to this trait? Update `ReadOnlyStore` and the
    // `WRITES` list and `every_write_method_is_covered` in `read_only_store_tests.rs`.
    /// Inserts `doc`, returning its `_id` (generated when absent).
    async fn insert(&self, ns: &Namespace, doc: Document) -> Result<Bson>;
    /// Replaces the document with `_id == id`; `NotFound` if none matches.
    async fn replace(&self, ns: &Namespace, id: &Bson, doc: Document) -> Result<()>;
    /// Deletes the document with `_id == id`; `NotFound` if none matches.
    async fn delete(&self, ns: &Namespace, id: &Bson) -> Result<()>;

    /// Whether writes through this store are refused (a read-only connection). The default,
    /// for stores that never lock, is `false`.
    fn is_read_only(&self) -> bool {
        false
    }

    /// Whether the server answers right now: a cheap round trip on this store's own connections.
    /// The runtime asks it to tell one lost connection from a server that cannot be reached.
    /// The default (no network) always answers.
    async fn ping(&self) -> Result<()> {
        Ok(())
    }

    /// How the server is deployed, if it can be read. Informational: a failure is `None`.
    async fn topology(&self) -> Result<Option<Topology>> {
        Ok(None)
    }

    /// The server's version string, if it can be read. Informational: a failure is `None`.
    async fn server_version(&self) -> Result<Option<String>> {
        Ok(None)
    }

    /// Applies `ops` (unordered, no ordering guarantee between them) and returns one outcome
    /// per op, index-aligned. `Err` only when the call as a whole failed (connection,
    /// authorization): then nothing may be assumed written.
    async fn bulk_write(&self, _ns: &Namespace, _ops: Vec<WriteOp>) -> Result<Vec<WriteOutcome>> {
        Err(CoreError::Unsupported(
            "this store cannot write in bulk".into(),
        ))
    }

    /// Estimated number of documents (fast, approximate). A missing collection counts as 0.
    async fn estimated_count(&self, _ns: &Namespace) -> Result<u64> {
        Err(CoreError::Unsupported(
            "this store cannot count documents".into(),
        ))
    }

    /// Documents matching `filter` whose key tuple is at or after `from` (all of them when
    /// `None`), in ascending key order under BINARY (simple) collation, at most `limit`.
    /// The start key is INCLUDED so a caller can detect a duplicate that straddles two batches.
    /// A document missing a key field yields `CompareKeyMissing`; an unusable key value
    /// yields `CompareKeyInvalid`. A missing collection behaves as empty.
    async fn scan_sorted(
        &self,
        _ns: &Namespace,
        _filter: &Document,
        _key: &KeySpec,
        _from: Option<&KeyTuple>,
        _limit: u32,
    ) -> Result<Vec<Document>> {
        Err(CoreError::Unsupported(
            "this store cannot scan in key order".into(),
        ))
    }

    /// Like [`scan_sorted`](Self::scan_sorted) but the read is served by the PRIMARY, whatever
    /// read preference the connection has. Used to re-verify documents right before a write, so
    /// a lagging secondary cannot make stale data look current. The default delegates to
    /// `scan_sorted` (stores without replicas have nothing to choose).
    async fn scan_sorted_primary(
        &self,
        ns: &Namespace,
        filter: &Document,
        key: &KeySpec,
        from: Option<&KeyTuple>,
        limit: u32,
    ) -> Result<Vec<Document>> {
        self.scan_sorted(ns, filter, key, from, limit).await
    }

    /// Whether an index can serve `scan_sorted` for `key`. A missing collection is `Indexed`
    /// (there is nothing to sort).
    async fn key_index_status(&self, _ns: &Namespace, _key: &KeySpec) -> Result<IndexStatus> {
        Err(CoreError::Unsupported(
            "this store cannot inspect indexes".into(),
        ))
    }

    /// The collections of `db` with their kind (`system.*` included).
    async fn list_collection_kinds(&self, _db: &str) -> Result<Vec<(String, CollectionKind)>> {
        Err(CoreError::Unsupported(
            "this store cannot list collection kinds".into(),
        ))
    }

    /// Key tuples shared by two or more documents matching `filter`, at most `limit`, most
    /// frequent first (ties in key order). Documents lacking a key field are not counted. A
    /// missing collection has no duplicates.
    async fn duplicate_keys(
        &self,
        _ns: &Namespace,
        _filter: &Document,
        _key: &KeySpec,
        _limit: u32,
    ) -> Result<Vec<DuplicateGroup>> {
        Err(CoreError::Unsupported(
            "this store cannot find duplicate keys".into(),
        ))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn query_default_is_first_page_with_empty_filter() {
        let q = Query::default();
        assert!(q.filter.is_empty());
        assert!(q.sort.is_none() && q.projection.is_none());
        assert_eq!((q.skip, q.limit), (0, PAGE_SIZE));
    }
}
